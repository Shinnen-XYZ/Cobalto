CREATE TABLE app_users (
    id UUID PRIMARY KEY,
    full_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE ledger_accounts (
    id UUID PRIMARY KEY,
    account_type VARCHAR(16) NOT NULL CHECK (account_type IN ('WALLET', 'SYSTEM')),
    owner_user_id UUID REFERENCES app_users(id),
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT uq_account_owner_currency UNIQUE (owner_user_id, currency),
    CONSTRAINT ck_account_owner_type CHECK (
        (account_type = 'WALLET' AND owner_user_id IS NOT NULL)
        OR (account_type = 'SYSTEM' AND owner_user_id IS NULL)
    )
);

CREATE TABLE ledger_transactions (
    id UUID PRIMARY KEY,
    type VARCHAR(32) NOT NULL,
    actor_user_id UUID NOT NULL REFERENCES app_users(id),
    idempotency_key VARCHAR(80) NOT NULL,
    request_fingerprint VARCHAR(64),
    currency VARCHAR(3) NOT NULL,
    description VARCHAR(160) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_ledger_idempotency UNIQUE (actor_user_id, idempotency_key)
);

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id UUID NOT NULL REFERENCES ledger_transactions(id),
    account_id UUID NOT NULL REFERENCES ledger_accounts(id),
    entry_type VARCHAR(8) NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount NUMERIC(19, 4) NOT NULL CHECK (amount > 0)
);

CREATE INDEX ix_ledger_entries_account ON ledger_entries(account_id);
CREATE INDEX ix_ledger_transactions_actor_created ON ledger_transactions(actor_user_id, created_at DESC);

