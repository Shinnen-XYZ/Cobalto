CREATE FUNCTION enforce_balanced_ledger_transaction() RETURNS TRIGGER AS $$
DECLARE
    transaction_currency VARCHAR(3);
    debit_total NUMERIC(19, 4);
    credit_total NUMERIC(19, 4);
BEGIN
    SELECT currency INTO transaction_currency
    FROM ledger_transactions WHERE id = NEW.transaction_id;

    SELECT
        COALESCE(SUM(amount) FILTER (WHERE entry_type = 'DEBIT'), 0),
        COALESCE(SUM(amount) FILTER (WHERE entry_type = 'CREDIT'), 0)
    INTO debit_total, credit_total
    FROM ledger_entries WHERE transaction_id = NEW.transaction_id;

    IF debit_total <> credit_total THEN
        RAISE EXCEPTION 'Ledger transaction % is not balanced', NEW.transaction_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM ledger_entries e
        JOIN ledger_accounts a ON a.id = e.account_id
        WHERE e.transaction_id = NEW.transaction_id
          AND a.currency <> transaction_currency
    ) THEN
        RAISE EXCEPTION 'Ledger transaction % mixes currencies', NEW.transaction_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER ct_ledger_transaction_balanced
AFTER INSERT OR UPDATE ON ledger_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_balanced_ledger_transaction();

CREATE FUNCTION reject_ledger_mutation() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Ledger records are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_ledger_entries_immutable
BEFORE UPDATE OR DELETE ON ledger_entries
FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();

CREATE TRIGGER tr_ledger_transactions_immutable
BEFORE UPDATE OR DELETE ON ledger_transactions
FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();
